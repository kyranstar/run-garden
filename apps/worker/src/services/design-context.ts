/** An op still the athlete's to decide (coach-runs.ts' alsoOpen rule, R2): undecided, refused at approval, or being applied. */
const OPEN_OP = sql.raw(
  `json_extract(o.value, '$.kind') IN ('doc_workout', 'plan_adjust') ` +
    `AND (json_extract(o.value, '$.outcome') IS NULL OR json_extract(o.value, '$.outcome.status') IN ('refused', 'applying'))`,
);

/** A reviewer run's draft day: the op it reviews (its candidate while a revision is under review, else the op itself). */
function draftDateSql(userId: string, reviewerId: string): SQL {
  const ops = (p: string) => sql.raw(`json_each(case when json_valid(${p}.ops) then ${p}.ops else '[]' end)`);
  return sql`(select coalesce(
      (select json_extract(o.value, '$.candidate.date') from ${coachProposals} p, ${ops("p")} o
        where p.user_id = ${userId} and p.id = json_extract(r.state, '$.reviewOf.proposalId') and json_extract(o.value, '$.candidate.reviewRunId') = r.id),
      (select json_extract(o.value, '$.date') from ${coachProposals} p, ${ops("p")} o
        where p.user_id = ${userId} and p.id = json_extract(r.state, '$.reviewOf.proposalId') and json_extract(o.value, '$.reviewRunId') = r.id))
    from ${coachRuns} r where r.id = ${reviewerId} and r.user_id = ${userId} and json_valid(r.state))`;
}

async function read(db: Db, userId: string, now: Date, horizonEnd: (today: string) => string, run: Pick<DesignRun, "id" | "role">): Promise<Reads> {
  const { profile, prefs } = await loadProfileWithPreferences(db, userId);
  const tz = zoneOrUtc(profile.timezone);
  const today = todayInZone(tz, now);
  const since = addDays(today, -(WINDOW_DAYS - 1));
  // Proposals are stamped in UTC: the window still starts at the athlete's own midnight, like every other window here.
  const sinceInstant = startOfLocalDate(tz, since);
  const todayInstant = startOfLocalDate(tz, today);
  const activeProfiles = profile.conditions.filter((c) => c.active).map((c) => c.profileId);
  const cp = coachProposals;
  const designPrefix = "dp-";
  const day = sql`substr(coalesce(${activities.startTimeLocal}, ${activities.startTime}), 1, 10)`;

  const [checks, objectiveRows, memory, plan, answers, history, countRows] = await Promise.all([
    db
      .select({ id: conditionChecks.id, profileId: conditionChecks.profileId, value: conditionChecks.value, feelingOff: conditionChecks.feelingOff, at: conditionChecks.at })
      .from(conditionChecks)
      .where(and(eq(conditionChecks.userId, userId), eq(conditionChecks.localDate, today), inArray(conditionChecks.kind, ["daily", "pre"]))),
    db
      .select({ id: objectives.id, title: objectives.title })
      .from(objectives)
      .where(and(eq(objectives.userId, userId), eq(objectives.status, "active")))
      .orderBy(asc(objectives.sort), asc(objectives.createdAt), asc(objectives.id)),
    memoryCore(db, userId, today),
    db
      .select({
        id: plannedWorkouts.id,
        date: plannedWorkouts.effectiveDate,
        time: plannedWorkouts.effectiveTime,
        category: plannedWorkouts.category,
        subtype: plannedWorkouts.qualitySubtype,
        sport: plannedWorkouts.sport,
        origin: plannedWorkouts.origin,
        state: plannedWorkouts.completionState,
        seconds: sql<number>`coalesce(${plannedWorkouts.sourceEstimatedDurationSeconds}, ${plannedWorkouts.fallbackEstimatedDurationSeconds}, ${plannedWorkouts.calendarBlockDurationSeconds})`,
      })
      .from(plannedWorkouts)
      .where(
        and(
          eq(plannedWorkouts.userId, userId),
          isNull(plannedWorkouts.archivedAt),
          gte(plannedWorkouts.effectiveDate, today),
          lte(plannedWorkouts.effectiveDate, horizonEnd(today)),
        ),
      )
      .orderBy(asc(plannedWorkouts.effectiveDate), asc(plannedWorkouts.effectiveTime), asc(plannedWorkouts.id)),
    db
      .select({ questionId: athleteAnswers.questionId, n: sql<number>`count(*)`, last: sql<string | null>`max(${athleteAnswers.localDate})` })
      .from(athleteAnswers)
      .where(and(eq(athleteAnswers.userId, userId), gte(athleteAnswers.localDate, since), lte(athleteAnswers.localDate, today)))
      .groupBy(athleteAnswers.questionId),
    db.all(sql`
      select case when ${activities.sport} in ('run', 'strength', 'yoga') then ${activities.sport} else 'other' end as kind,
             sum(case when ${day} >= ${since} then 1 else 0 end) as recent,
             max(${day}) as last
      from ${activities} where ${activities.userId} = ${userId}
      group by kind`) as Promise<Array<{ kind: string; recent: number; last: string | null }>>,
    db.all(sql`
      select
        (select count(*) from ${performedSessions} where ${performedSessions.userId} = ${userId}
           and ${performedSessions.payloadHash} != ${PENDING_HASH} and ${performedSessions.localDate} >= ${since}) as sessions,
        (select max(${performedSessions.localDate}) from ${performedSessions} where ${performedSessions.userId} = ${userId}
           and ${performedSessions.payloadHash} != ${PENDING_HASH}) as sessionsLast,
        (select count(*) from ${providerConnections} where ${providerConnections.userId} = ${userId} and ${providerConnections.provider} = 'coros') as watchConnected,
        (select max(${providerConnections.lastSyncAt}) from ${providerConnections} where ${providerConnections.userId} = ${userId}
           and ${providerConnections.provider} = 'coros') as watchSynced,
        (select json_group_array(json_object('title', title, 'date', d, 'c', c)) from (
           select title, d, c from (
             select p.title as title, p.created_at as c, p.id as i, (select min(json_extract(o.value, '$.date')) from json_each(p.ops) o
                 where ${OPEN_OP} and json_extract(o.value, '$.date') >= ${today}) as d
             from ${cp} p where p.user_id = ${userId} and substr(p.id, 1, ${designPrefix.length}) = ${designPrefix}
               and p.status in ('pending', 'partially_approved') and json_valid(p.ops) and p.expires_at >= ${today})
           where d is not null order by c desc, i desc limit ${OPEN_LISTED + 1})) as open,
        (select json_object('n', count(*), 'reasons', sum(case when json_extract(o.value, '$.outcome.reason') is not null then 1 else 0 end))
           from ${cp} p, json_each(case when json_valid(p.ops) then p.ops else '[]' end) o
           where p.user_id = ${userId} and p.status != 'rehearsal' and json_extract(o.value, '$.kind') = 'doc_workout'
             and json_extract(o.value, '$.outcome.status') = 'declined' and json_extract(o.value, '$.outcome.at') >= ${todayInstant}) as declined,
        ${run.role === "reviewer" ? draftDateSql(userId, run.id) : sql`null`} as draftDate,
        (select count(*) from ${coachProposals} where ${coachProposals.userId} = ${userId}
           and ${coachProposals.status} != 'rehearsal' and ${coachProposals.createdAt} >= ${sinceInstant}) as proposals,
        (select max(${coachProposals.createdAt}) from ${coachProposals} where ${coachProposals.userId} = ${userId}
           and ${coachProposals.status} != 'rehearsal' and ${coachProposals.createdAt} >= ${sinceInstant}) as proposalsLast,
        (select max(${dailyHealth.date}) from ${dailyHealth} where ${dailyHealth.userId} = ${userId} and ${dailyHealth.hrv} is not null) as hrvLast,
        (select max(${dailyHealth.date}) from ${dailyHealth} where ${dailyHealth.userId} = ${userId}
           and ${dailyHealth.restingHeartRate} is not null) as rhrLast,
        (select max(${sleepRecords.date}) from ${sleepRecords} where ${sleepRecords.userId} = ${userId}) as sleepLast`) as Promise<
      Array<Reads["counts"] & { open: string | null; declined: string | null; draftDate: string | null }>
    >,
  ]);
  const { open: openJson, declined: declinedJson, draftDate: rawDraft, ...counts } = countRows[0]!;
  const open = parsedArray(openJson)
    .flatMap((x) => {
      const o = x as { title?: unknown; date?: unknown; c?: unknown };
      return typeof o.date === "string" ? [{ title: typeof o.title === "string" ? o.title : "", date: o.date, c: String(o.c ?? "") }] : [];
    })
    // The aggregate's input order is SQLite's to choose: newest first again, here.
    .sort((a, b) => (a.c < b.c ? 1 : a.c > b.c ? -1 : 0))
    .map(({ title, date }) => ({ title, date }));
  const declined = parsedJson(declinedJson) as { n?: unknown; reasons?: unknown } | null;
  const draftDate = typeof rawDraft === "string" && /^\d{4}-\d{2}-\d{2}$/.test(rawDraft) ? rawDraft : null;
  return {
    profile,
    prefs,
    today,
    tz,
    activeProfiles,
    checks,
    objectives: objectiveRows,
    memory,
    plan,
    answers,
    history,
    counts: { ...counts, proposalsLast: counts.proposalsLast ? todayInZone(tz, new Date(counts.proposalsLast)) : null },
    open,
    declinedToday: { n: Number(declined?.n ?? 0) || 0, reasons: Number(declined?.reasons ?? 0) || 0 },
    draftDate,
    around: draftDate ? await daysAround(db, userId, { tz, units: prefs.units === "mi" ? "mi" : "km", weightUnit: prefs.weightUnit }, today, draftDate) : null,
  };
}

/** How far either side of a reviewer's draft day it is shown the plan and the log (fix wave 13, I9). */
const AROUND_DAYS = 2;

/** The days around a reviewer's draft day: the plan's rows and the sessions and activities of those days. One statement. */
async function daysAround(db: Db, userId: string, ctx: DoneCtx, today: string, date: string): Promise<NonNullable<Reads["around"]>> {
  const from = addDays(date, -AROUND_DAYS);
  const to = addDays(date, AROUND_DAYS);
  // What was done: never past today. Sessions, and the activities around (one session per activity, by doneEntries).
  const doneTo = to < today ? to : today;
  const [sTerm, , , aTerm] = doneTerms(userId, sessionsWhere(userId, sql`${performedSessions.localDate} between ${from} and ${doneTo}`), {
    activitiesWhere: activitiesAround(from, doneTo),
  });
  const rows = await readTagged(db, [sTerm!, aTerm!, planTerm(userId, sql`${plannedWorkouts.effectiveDate} between ${from} and ${to}`)]);
  const done = from <= doneTo ? doneEntries({ sessions: rows.get("s"), activities: rows.get("a") }, ctx, { from, to: doneTo }) : [];
  return { plan: rows.get("p") ?? [], done };
}

