/**
 * THE COACH DESIGNER'S OPENING CONTEXT (Stage 3 spec §3; principles §6.3): only what the agent must know, laid out so
 * the stable part caches. Everything else — history, balance, soreness, feedback, the plan, readiness, the library,
 * past workouts and proposals, older memory — the agent reaches by tool call when it decides it needs it.
 *
 * `buildDesignContext` answers `{ system, header }`. The step loop (coach-runs.ts) sends `system` as the system blocks
 * and `header` as the run's first user message. The cache order is tools → system → messages, so:
 *  1. the shared prefix (design-prompt.ts `SHARED_PROMPT`) — byte-identical for every run; a breakpoint;
 *  2. the role block (main, designer or reviewer — the reviewer's carries the rubric);
 *  3. the athlete's profile summary — goals in their own words, focus areas, active objectives with ids, the default
 *     place; a breakpoint (it changes only when the athlete edits their profile);
 *  4. the pinned memory — pinned items, then recent facts and rules, at most 20 (memory-core.ts: live items only, never a
 *     rehearsal run's).
 * Nothing per-request is ever in `system`: the date, the readings, the request would break the cache for every later
 * run. They go in `header`: today (date, weekday, time, timezone), units, each active condition profile's rules —
 * generated by the profile itself (`describeRules`), so prompt and code cannot disagree — with today's reading or
 * "none today", one line of today's plan, the events within the scope's horizon, the scope, the availability index
 * (counts and dates, never contents), and the request.
 *
 * Untrusted text — the request, the athlete's words in the profile, memory items, a sub-run's brief — goes in only
 * through `markUntrusted`, the one marker the shared prefix explains; nothing inside it can close its block.
 *
 * Budget: `DESIGN_CONTEXT_STATEMENTS` D1 statements, whatever the account holds (a counting test pins it), well inside
 * the step's 45 with the model call and the tool calls.
 */
