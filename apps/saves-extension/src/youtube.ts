import { transcriptText, type Chapter, type PostSubmit, type SaveErrorCode, type Segment } from "@rg/saves";
import { hashtagsOf } from "./feed.js";

// A YOUTUBE VIDEO, READ BY PURE FUNCTIONS (design 2026-11-05 §5.2). The page script (youtube-reader.ts) only hands over
// what the page holds — the player's response, the player bar's markers, the captions the player fetched, the
// transcript panel's rows — and everything is parsed here, defensively: YouTube's page is undocumented and changes.

export const YT_ORIGIN = "https://www.youtube.com";
export const watchUrl = (id: string): string => `${YT_ORIGIN}/watch?v=${id}`;

export interface CaptionTrack {
  languageCode: string;
  /** `asr`: generated by YouTube's speech recognition; null: uploaded by the creator. */
  kind: "asr" | null;
  name: string;
}
export interface YoutubeMeta {
  id: string;
  title: string;
  channel: { handle: string; name: string };
  lengthSec: number;
  description: string;
  publishedAt: string | null;
  /** A live stream that has ended (one live now is never read). */
  live: boolean;
  tracks: CaptionTrack[];
}
export type YoutubeFailure = { ok: false; code: SaveErrorCode; message: string };

type Obj = Record<string, unknown>;
const isObj = (v: unknown): v is Obj => typeof v === "object" && v !== null && !Array.isArray(v);
const str = (v: unknown): string | null => (typeof v === "string" ? v : null);
const oneLine = (s: string): string => s.replace(/\s+/g, " ").trim();

const DESCRIPTION_MAX = 5_000;
const TITLE_MAX = 200;
const HANDLE_MAX = 64;
const NAME_MAX = 120;
const REASON_MAX = 120;
const CHAPTERS_MAX = 100;
const CHAPTER_TITLE_MAX = 100;

export const LIVE_NOW = "Live now — try after it ends";
export const PLAYER_DIDNT_LOAD = "The player didn't load";

/** Plain words a renderer's text holds (`simpleText`, or its `runs`). */
function textOf(v: unknown): string {
  if (typeof v === "string") return v;
  if (!isObj(v)) return "";
  if (typeof v.simpleText === "string") return v.simpleText;
  if (Array.isArray(v.runs)) return v.runs.map((r) => (isObj(r) ? (str(r.text) ?? "") : "")).join("");
  return "";
}

const parsed = (raw: unknown): unknown => {
  if (typeof raw !== "string") return raw;
  try {
    return JSON.parse(raw);
  } catch {
    return null;
  }
};

/**
 * The player's response (`#movie_player.getPlayerResponse()`, as JSON or an object) as the video's details, or why it
 * can't be read, in plain words. Captions missing is not a failure: the tracks are then empty.
 */
export function parsePlayer(raw: unknown, expectId: string): { ok: true; meta: YoutubeMeta } | YoutubeFailure {
  const pr = parsed(raw);
  if (!isObj(pr) || !isObj(pr.videoDetails)) return { ok: false, code: "unknown", message: PLAYER_DIDNT_LOAD };
  const vd = pr.videoDetails;
  const play = isObj(pr.playabilityStatus) ? pr.playabilityStatus : {};
  const status = str(play.status) ?? "OK";
  const errorScreen = isObj(play.errorScreen) && isObj(play.errorScreen.playerErrorMessageRenderer) ? play.errorScreen.playerErrorMessageRenderer : null;
  const reason = oneLine(str(play.reason) ?? textOf(errorScreen?.reason) ?? "").slice(0, REASON_MAX);
  if (status === "LOGIN_REQUIRED") {
    return { ok: false, code: "unplayable", message: /\bage\b/i.test(reason) ? "Age-restricted" : "YouTube asked to sign in" };
  }
  if (status === "AGE_CHECK_REQUIRED" || status === "CONTENT_CHECK_REQUIRED") return { ok: false, code: "unplayable", message: "Age-restricted" };
  if (status === "ERROR") return { ok: false, code: "gone", message: "The video is gone" };
  if (status === "LIVE_STREAM_OFFLINE" || status === "LIVE_STREAM" || vd.isLive === true || vd.isUpcoming === true) {
    return { ok: false, code: "unplayable", message: LIVE_NOW };
  }
  if (status !== "OK") return { ok: false, code: "unplayable", message: reason || "YouTube won't play it" };
  if (str(vd.videoId) !== expectId) return { ok: false, code: "unknown", message: "The player showed another video" };

  const micro = isObj(pr.microformat) && isObj(pr.microformat.playerMicroformatRenderer) ? pr.microformat.playerMicroformatRenderer : {};
  const handle = /\/(@[^/?#]+)/.exec(str(micro.ownerProfileUrl) ?? "")?.[1] ?? str(vd.channelId) ?? "";
  const list = isObj(pr.captions) && isObj(pr.captions.playerCaptionsTracklistRenderer) ? pr.captions.playerCaptionsTracklistRenderer.captionTracks : null;
  const tracks: CaptionTrack[] = Array.isArray(list)
    ? list.flatMap((t) => {
        if (!isObj(t) || !str(t.languageCode)) return [];
        return [{ languageCode: t.languageCode as string, kind: t.kind === "asr" ? ("asr" as const) : null, name: textOf(t.name) }];
      })
    : [];
  const length = Number(vd.lengthSeconds);
  return {
    ok: true,
    meta: {
      id: expectId,
      title: oneLine(str(vd.title) ?? ""),
      channel: { handle: handle.slice(0, HANDLE_MAX), name: oneLine(str(vd.author) ?? "").slice(0, NAME_MAX) },
      lengthSec: Number.isFinite(length) && length > 0 ? Math.round(length) : 0,
      description: str(vd.shortDescription) ?? "",
      publishedAt: (str(micro.publishDate) ?? str(micro.uploadDate))?.slice(0, 40) ?? null,
      live: vd.isLiveContent === true,
      tracks,
    },
  };
}

const lang = (code: string): string => code.split("-")[0]!.toLowerCase();

/**
 * The track to read: the creator's own in the video's language (the auto-generated track's language is the one spoken),
 * else the auto-generated one; with no auto-generated track, the first uploaded one.
 */
export function pickTrack(tracks: readonly CaptionTrack[]): CaptionTrack | null {
  const asr = tracks.find((t) => t.kind === "asr");
  if (asr) return tracks.find((t) => t.kind === null && lang(t.languageCode) === lang(asr.languageCode)) ?? asr;
  return tracks.find((t) => t.kind === null) ?? null;
}

/** Of the captions the player fetched, the one for `track` (its language and kind), else the first that holds anything. */
export function pickCapture(captures: readonly { url: string; text: string }[], track: CaptionTrack): string | null {
  const full = captures.filter((c) => c.text.trim().length > 0);
  const params = (url: string) => {
    try {
      return new URL(url, YT_ORIGIN).searchParams;
    } catch {
      return new URLSearchParams();
    }
  };
  const match = full.find((c) => {
    const p = params(c.url);
    const l = p.get("lang") ?? p.get("tlang");
    return l !== null && lang(l) === lang(track.languageCode) && (p.get("kind") === "asr") === (track.kind === "asr");
  });
  return (match ?? full[0])?.text ?? null;
}

const tenth = (sec: number): number => Math.round(sec * 10) / 10;
const ENTITIES: Readonly<Record<string, string>> = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " " };
const decode = (s: string): string =>
  s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (whole, e: string) => {
    if (e[0] === "#") {
      const n = e[1] === "x" || e[1] === "X" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
      return Number.isFinite(n) ? String.fromCodePoint(n) : whole;
    }
    return ENTITIES[e.toLowerCase()] ?? whole;
  });

/**
 * A captured caption track as segments: json3 (`events[].segs[].utf8`, `tStartMs`), or the XML formats YouTube also
 * serves (`<text start>`, srv3's `<p t>`). Empty lines go; nothing readable is no segments.
 */
export function captureSegments(text: string): Segment[] {
  const body = text.trim();
  if (body.startsWith("{")) {
    const doc = parsed(body);
    const events = isObj(doc) && Array.isArray(doc.events) ? doc.events : [];
    return events.flatMap((e): Segment[] => {
      if (!isObj(e) || !Array.isArray(e.segs) || typeof e.tStartMs !== "number") return [];
      const words = oneLine(e.segs.map((s) => (isObj(s) ? (str(s.utf8) ?? "") : "")).join(""));
      return words ? [[tenth(e.tStartMs / 1000), words]] : [];
    });
  }
  const out: Segment[] = [];
  for (const m of body.matchAll(/<text\b[^>]*\bstart="([\d.]+)"[^>]*>([\s\S]*?)<\/text>/g)) {
    const words = oneLine(decode(m[2]!.replace(/<[^>]*>/g, "")));
    if (words) out.push([tenth(Number(m[1])), words]);
  }
  if (out.length) return out;
  for (const m of body.matchAll(/<p\b[^>]*\bt="(\d+)"[^>]*>([\s\S]*?)<\/p>/g)) {
    const words = oneLine(decode(m[2]!.replace(/<[^>]*>/g, "")));
    if (words) out.push([tenth(Number(m[1]) / 1000), words]);
  }
  return out;
}

/** "1:02:03", "4:05" or "0:05" as seconds; null for anything else. */
export function clockSeconds(text: string): number | null {
  const m = /^\s*(?:(\d{1,2}):)?(\d{1,2}):(\d{2})\s*$/.exec(text);
  if (!m) return null;
  const s = Number(m[3]);
  if (s > 59) return null;
  return Number(m[1] ?? 0) * 3600 + Number(m[2]) * 60 + s;
}

/** The transcript panel's rows (the fallback) as segments. */
export function panelSegments(rows: readonly { time: string; text: string }[]): Segment[] {
  return rows.flatMap((r): Segment[] => {
    const at = clockSeconds(r.time);
    const words = oneLine(r.text);
    return at !== null && words ? [[at, words]] : [];
  });
}

const chapter = (start: number, title: string): Chapter => ({ start, title: oneLine(title).slice(0, CHAPTER_TITLE_MAX) });

/** The player bar's chapters (`markersMap`, as JSON): the creator's (`DESCRIPTION_CHAPTERS`) before the automatic ones. */
export function chaptersFromMarkers(markersJson: string | null): Chapter[] {
  const doc = markersJson ? parsed(markersJson) : null;
  if (!Array.isArray(doc)) return [];
  const byKey = (key: string) => doc.find((m) => isObj(m) && m.key === key);
  const entry = byKey("DESCRIPTION_CHAPTERS") ?? byKey("AUTO_CHAPTERS");
  const list = isObj(entry) && isObj(entry.value) && Array.isArray(entry.value.chapters) ? entry.value.chapters : [];
  return list
    .flatMap((c): Chapter[] => {
      const r = isObj(c) && isObj(c.chapterRenderer) ? c.chapterRenderer : null;
      const ms = r ? Number(r.timeRangeStartMillis) : NaN;
      const title = r ? textOf(r.title) : "";
      return Number.isFinite(ms) && ms >= 0 && title.trim() ? [chapter(Math.round(ms / 100) / 10, title)] : [];
    })
    .slice(0, CHAPTERS_MAX);
}

const STAMP = /(?:^|[\s(\[])((?:\d{1,2}:)?\d{1,2}:\d{2})(?=$|[\s)\]\-–—:|•])/;

/**
 * Chapters from the description, by YouTube's own rule: timestamps starting at 0:00, at least three, ascending, each
 * at least 10 s after the one before. Anything else is no chapters.
 */
export function chaptersFromDescription(description: string): Chapter[] {
  const found: Chapter[] = [];
  for (const line of description.split("\n")) {
    const m = STAMP.exec(line);
    if (!m) continue;
    const at = clockSeconds(m[1]!);
    if (at === null) continue;
    const title = line.replace(m[0], " ").replace(/^[\s\-–—:|•)\]]+|[\s\-–—:|•(\[]+$/g, "");
    found.push(chapter(at, title || m[1]!));
  }
  if (found.length < 3 || found[0]!.start !== 0) return [];
  for (let i = 1; i < found.length; i++) if (found[i]!.start - found[i - 1]!.start < 10) return [];
  return found.slice(0, CHAPTERS_MAX);
}

/** A video as the app's submit, with the read's facts (design 2026-11-05 §5.3). */
export function toYoutubeSubmit(
  meta: YoutubeMeta,
  transcript: { track: CaptionTrack; segments: readonly Segment[]; via: "captured" | "panel" } | null,
  chapters: { list: readonly Chapter[]; from: "player" | "description" | null },
  extVersion: string,
  ms: number,
): PostSubmit {
  const text = transcript && transcript.segments.length ? transcriptText(transcript.segments) : null;
  const kept = text && text.text ? transcript : null;
  const kind = kept?.track.kind === "asr" ? ("auto" as const) : ("uploaded" as const);
  const description = meta.description.slice(0, DESCRIPTION_MAX);
  return {
    source: "youtube",
    key: meta.id,
    url: watchUrl(meta.id),
    creator: { handle: meta.channel.handle, ...(meta.channel.name ? { name: meta.channel.name } : {}) },
    caption: description,
    hashtags: hashtagsOf(description),
    mediaType: "video",
    postedAt: meta.publishedAt,
    origin: "pasted",
    title: meta.title.slice(0, TITLE_MAX),
    // An unknown length is no length, never zero: the app would take a zero as "short enough to watch" (final review F5).
    ...(meta.lengthSec > 0 ? { durationSec: Math.min(86_400, meta.lengthSec) } : {}),
    chapters: chapters.list.slice(0, CHAPTERS_MAX),
    ...(kept && text ? { transcript: { lang: kept.track.languageCode.slice(0, 20), kind, text: text.text, cut: text.cut } } : {}),
    live: meta.live,
    readFacts: {
      via: "pasted",
      extVersion,
      coverSent: false,
      mediaCount: 1,
      youtube: {
        captions: kept ? { lang: kept.track.languageCode.slice(0, 20), kind } : null,
        segments: kept ? kept.segments.length : 0,
        transcriptChars: kept && text ? text.text.length : 0,
        chapters: Math.min(chapters.list.length, CHAPTERS_MAX),
        chaptersFrom: chapters.list.length ? chapters.from : null,
        via: kept ? kept.via : null,
        ms: Math.min(600_000, Math.max(0, Math.round(ms))),
      },
    },
  };
}
